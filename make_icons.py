def save_as_ico(pixmap, filepath):
    temp_png = filepath + ".tmp.png"
    pixmap.save(temp_png, "PNG")
    with open(temp_png, "rb") as f:
        png_bytes = f.read()
    if os.path.exists(temp_png):
        os.remove(temp_png)
    
    header = struct.pack('<HHH', 0, 1, 1)
    entry = struct.pack('<BBBBHHII', 0, 0, 0, 0, 1, 32, len(png_bytes), 22)
    with open(filepath, "wb") as f:
        f.write(header + entry + png_bytes)

def create_base_canvas():
    pixmap = QPixmap(256, 256)
    pixmap.fill(Qt.GlobalColor.transparent)
    p = QPainter(pixmap)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)

    grad_bg = QLinearGradient(0, 0, 256, 256)
    grad_bg.setColorAt(0.0, QColor(20, 22, 32, 235))
    grad_bg.setColorAt(1.0, QColor(10, 12, 18, 250))
    
    path = QPainterPath()
    path.addRoundedRect(16, 16, 224, 224, 52, 52)
    p.fillPath(path, grad_bg)

    pen = QPen(QColor(0, 240, 255, 220), 5)
    p.setPen(pen)
    p.drawPath(path)
    return pixmap, p

